def ui(language, key, **values):
    index = LANGS.index(language) if language in LANGS else 1
    return LABELS[key][index].format(**values)


def validation_label(language, error):
    key = str(error)
    return ui(language, key if key in LABELS else "validation")


def diagnostic_label(language, code):
    key = code if code in LABELS and code.startswith("DS-") else "DS-UNKNOWN"
    return key + ": " + ui(language, key)
